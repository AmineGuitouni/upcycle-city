        static Light BuildSystems(Transform root, Material sky, EcosystemBalance balance, out CrowdCharacterLibrary charLib)
        {
            var sunGo = new GameObject("Directional Sun");
            sunGo.transform.SetParent(root);
            sunGo.transform.rotation = Quaternion.Euler(46f, -32f, 0f);   // morning light down the avenue
            Light sun = sunGo.AddComponent<Light>();
            sun.type = LightType.Directional;
            sun.intensity = 1.5f;
            sun.shadows = LightShadows.Soft;

            if (sky != null)
                RenderSettings.skybox = sky;

            VolumeProfile cityGrade = AssetDatabase.LoadAssetAtPath<VolumeProfile>("Assets/UpcycleCity/Settings/CityGrade.asset");
            if (cityGrade != null)
            {
                var gradeGo = new GameObject("GlobalVolume_CityGrade");
                gradeGo.transform.SetParent(root);
                Volume gradeVol = gradeGo.AddComponent<Volume>();
                gradeVol.isGlobal = true;
                gradeVol.priority = 0f;
                gradeVol.sharedProfile = cityGrade;
            }

            Volume smogVolume = null;
            VolumeProfile smogGrade = AssetDatabase.LoadAssetAtPath<VolumeProfile>("Assets/UpcycleCity/Settings/SmogGrade.asset");
            if (smogGrade != null)
            {
                var smogGo = new GameObject("GlobalVolume_SmogGrade");
                smogGo.transform.SetParent(root);
                smogVolume = smogGo.AddComponent<Volume>();
                smogVolume.isGlobal = true;
                smogVolume.priority = 1f;
                smogVolume.weight = 0.6f;
                smogVolume.sharedProfile = smogGrade;
            }

            var pollutionGo = new GameObject("PollutionController");
            pollutionGo.transform.SetParent(root);
            PollutionController pollutionController = pollutionGo.AddComponent<PollutionController>();
            using (var so = new SerializedObject(pollutionController))
            {
                so.FindProperty("pollution").floatValue = 0.65f;
                so.FindProperty("transitionTime").floatValue = 2.5f;
                so.FindProperty("profile").objectReferenceValue = AssetDatabase.LoadAssetAtPath<PollutionProfile>("Assets/UpcycleCity/Settings/PollutionProfile.asset");
                so.FindProperty("sun").objectReferenceValue = sun;
                so.FindProperty("smogVolume").objectReferenceValue = smogVolume;
                so.ApplyModifiedPropertiesWithoutUndo();
            }

            var ecoGo = new GameObject("CityEcosystemManager");
            ecoGo.transform.SetParent(root);
            ecoGo.AddComponent<CityEcosystemManager>().Configure(AssetDatabase.LoadAssetAtPath<WasteCatalog>(CatalogPath), globalTrashCap: 60, cityBalance: balance);
            ecoGo.AddComponent<EcosystemHUD>();

            var crowdSysGo = new GameObject("CrowdSystem");
            crowdSysGo.transform.SetParent(root);
            CrowdSystem crowdSystem = crowdSysGo.AddComponent<CrowdSystem>();
            using (var so = new SerializedObject(crowdSystem))
            {
                so.FindProperty("animatorController").objectReferenceValue =
                    AssetDatabase.LoadAssetAtPath<RuntimeAnimatorController>("Assets/UpcycleCity/Animation/CrowdAnimator.controller");
                so.FindProperty("animatedBudget").intValue = 36;
                so.FindProperty("animateDistance").floatValue = 90f;
                so.ApplyModifiedPropertiesWithoutUndo();
            }
            charLib = AssetDatabase.LoadAssetAtPath<CrowdCharacterLibrary>("Assets/UpcycleCity/Settings/CrowdCharacters.asset");

            // The shop window (UI Toolkit) and the EventSystem that routes mouse, touch and gamepad to it
            var shopUiGo = new GameObject("ShopUI");
            shopUiGo.transform.SetParent(root);
            shopUiGo.AddComponent<ShopUI>().Configure(
                AssetDatabase.LoadAssetAtPath<PanelSettings>($"{UiDir}/UpcycleCityPanelSettings.asset"),
                AssetDatabase.LoadAssetAtPath<StyleSheet>($"{UiDir}/Shop.uss"));

            CraftingContentBuilder.Content craftingContent = CraftingContentBuilder.EnsureAll(overwriteExistingTuning: false);
            var stockGo = new GameObject("TeamMaterialStock");
            stockGo.transform.SetParent(root);
            stockGo.AddComponent<TeamMaterialStock>().Configure(
                craftingContent.database,
                craftingContent.starterKit,
                applyKitOnStart: false,
                initialEnergy: 40,
                energyCap: 500,
                enableDebugActions: false);

            var craftUiGo = new GameObject("CraftingUI");
            craftUiGo.transform.SetParent(root);
            craftUiGo.AddComponent<CraftingUI>().Configure(
                craftingContent.uiConfig != null && craftingContent.uiConfig.PanelSettings != null
                    ? craftingContent.uiConfig.PanelSettings
                    : AssetDatabase.LoadAssetAtPath<PanelSettings>($"{UiDir}/UpcycleCityPanelSettings.asset"),
                AssetDatabase.LoadAssetAtPath<StyleSheet>($"{UiDir}/Crafting.uss"),
                debugButtons: false);

            var eventSystem = new GameObject("EventSystem");
            eventSystem.transform.SetParent(root);
            eventSystem.AddComponent<UnityEngine.EventSystems.EventSystem>();
            eventSystem.AddComponent<UnityEngine.InputSystem.UI.InputSystemUIInputModule>();
            return sun;
        }

