        static GameObject SetUpShop(Transform root, Dictionary<string, GameObject> buildings, string name, ShopCatalog catalog,
            RuntimeAnimatorController controller, KeeperSpot spot)
        {
            if (!buildings.TryGetValue(name, out GameObject building) || catalog == null)
                return null;

            // The shopkeeper: a rigged Vocations character idling behind the counter
            GameObject model = AssetDatabase.LoadAssetAtPath<GameObject>($"{ArtRigged}/{spot.model}.fbx");
            if (model != null)
            {
                var keeperGo = (GameObject)PrefabUtility.InstantiatePrefab(model, building.transform);
                keeperGo.name = $"Shopkeeper_{catalog.KeeperName.Replace(" ", "")}";
                keeperGo.transform.localPosition = spot.local;
                keeperGo.transform.localRotation = Quaternion.Euler(0f, spot.yaw, 0f);
                keeperGo.transform.SetParent(root, true);
                Animator animator = keeperGo.GetComponent<Animator>() ?? keeperGo.AddComponent<Animator>();
                animator.runtimeAnimatorController = controller;
                animator.applyRootMotion = false;

                CapsuleCollider capsule = keeperGo.AddComponent<CapsuleCollider>();
                capsule.center = new Vector3(0f, 0.9f, 0f);
                capsule.height = 1.8f;
                capsule.radius = 0.38f;

                Shopkeeper keeper = keeperGo.AddComponent<Shopkeeper>();
                keeper.Configure(animator, catalog);
                keeperGo.AddComponent<ShopCounter>().Configure(catalog, keeper);
                keeperGo.AddComponent<FocusHighlight>();
                GameLayers.SetLayerRecursively(keeperGo, GameLayers.Interactable);
            }
            else
            {
                Debug.LogWarning($"[Upcycle City] Shopkeeper model {spot.model} not found in {ArtRigged}.");
            }

            // Warm lamps over the room (three at most, no shadows: cheap enough for mobile)
            var markers = new List<Transform>();
            foreach (Transform child in building.GetComponentsInChildren<Transform>(true))
            {
                if (child.name.StartsWith("InteriorLight"))
                    markers.Add(child);
            }
            int[] picks = markers.Count >= 3 ? new[] { 0, markers.Count / 2, markers.Count - 1 } : new[] { 0, 1 };
            foreach (int i in picks)
            {
                if (i >= markers.Count)
                    continue;
                Light lamp = markers[i].gameObject.AddComponent<Light>();
                lamp.type = LightType.Point;
                lamp.range = 8f;
                lamp.intensity = 2.2f;
                lamp.color = new Color(1f, 0.9f, 0.76f);
                lamp.shadows = LightShadows.None;
            }

            // Citizens window-shop and drink coffee out front
            var poiGo = new GameObject($"POI_{catalog.ShopName}");
            poiGo.transform.SetParent(building.transform, false);
            poiGo.transform.localPosition = new Vector3(0f, 0f, 2.5f);
            poiGo.AddComponent<CitizenPointOfInterest>().Configure(spot.poi, catalog.ShopName, 6f);
            return building;
        }

        /// <summary>The RÉCUP weighing platform at the shop's ShopPoint: solid for E-deposits, a trigger for throws.</summary>
        static void CreateBuyBackScale(GameObject building)
        {
            Transform point = null;
            foreach (Transform child in building.GetComponentsInChildren<Transform>(true))
