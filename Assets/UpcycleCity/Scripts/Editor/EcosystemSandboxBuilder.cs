        /// <summary>Both rows of the avenue, the rows closing the square and the Bab Bhar end. Returns the shops by name.</summary>
        static Dictionary<string, GameObject> BuildStreetRows(Transform root)
        {
            var shops = new Dictionary<string, GameObject>();

            // West row faces east (+X), east row faces west (-X); listed south to north. The southern blocks end at
            // the cross street and reach back to the Bab Bhar end; the northern ones run from it past the square.
            PlaceRow(root, shops, -FacadeX, 90f, CrossStreetSouthZ - RowLength("bb_building_b", "bb_building_gate", "shop_recycling", "shop_cafe", "bb_building_d"),
                "bb_building_b", "bb_building_gate", "shop_recycling", "shop_cafe", "bb_building_d");
            PlaceRow(root, shops, -FacadeX, 90f, CrossStreetNorthZ, "bb_building_a", "bb_building_c", "bb_building_b", "bb_building_e",
                "bb_building_d", "bb_building_a", "bb_building_gate", "bb_building_b");
            PlaceRow(root, shops, FacadeX, -90f, CrossStreetSouthZ - RowLength("bb_building_d", "bb_building_e", "shop_tools", "shop_grocery", "bb_building_a"),
                "bb_building_d", "bb_building_e", "shop_tools", "shop_grocery", "bb_building_a");
            PlaceRow(root, shops, FacadeX, -90f, CrossStreetNorthZ, "bb_building_b", "bb_building_d", "bb_building_c", "bb_building_gate",
                "bb_building_e", "bb_building_a", "bb_building_c", "bb_building_d");

            // North row closes Place du 14 Janvier (faces south), south row is the Bab Bhar end (faces north)
            PlaceRowAcross(root, NorthRowZ, 180f, "bb_building_c", "bb_building_a", "bb_building_d");
            PlaceRowAcross(root, SouthRowZ, 0f, "bb_building_b", "bb_building_gate", "bb_building_e");
            return shops;
        }

        static void PlaceRow(Transform root, Dictionary<string, GameObject> shops, float x, float yaw, float startZ, params string[] names)
        {
            float z = startZ;
            foreach (string name in names)
            {
                float w = Widths[name];
                GameObject b = PlaceBuilding(name, root, new Vector3(x, 0f, z + w * 0.5f), yaw);
                if (b != null && name.StartsWith("shop_"))
                    shops[name] = b;
                z += w;
            }
        }

        static float RowLength(params string[] names)
        {
            float total = 0f;
            foreach (string name in names)
                total += Widths[name];
            return total;
        }

        /// <summary>A row across the avenue at <paramref name="z"/>, centred on it, listed west to east.</summary>
        static void PlaceRowAcross(Transform root, float z, float yaw, params string[] names)
        {
            float x = -RowLength(names) * 0.5f;
            foreach (string name in names)
            {
                float w = Widths[name];
                PlaceBuilding(name, root, new Vector3(x + w * 0.5f, 0f, z), yaw);
                x += w;
            }
        }

        static GameObject PlaceBuilding(string name, Transform parent, Vector3 front, float yaw, string group = null)
        {
            group ??= name == "clocktower" || name == "clocktower_fountain" ? "Landmarks" : "Buildings";
            string path = $"{ArtBourguiba}/{group}/{name}.fbx";
            GameObject asset = AssetDatabase.LoadAssetAtPath<GameObject>(path);
            if (asset == null)
            {
                Debug.LogWarning($"[Upcycle City] Missing {path}; run Tools/Blender/export_bourguiba.py.");
                return null;
            }
            var go = (GameObject)PrefabUtility.InstantiatePrefab(asset, parent);
            go.name = name;
            go.transform.SetPositionAndRotation(front, Quaternion.Euler(0f, yaw, 0f));
            AddMeshColliders(go);
            GameLayers.SetLayerRecursively(go, GameLayers.Environment);
            go.tag = GameTags.Environment;
            go.isStatic = true;
            return go;
        }

        static void AddMeshColliders(GameObject go)
        {
            foreach (MeshFilter filter in go.GetComponentsInChildren<MeshFilter>(true))
            {
                if (filter.sharedMesh == null || filter.GetComponent<Collider>() != null)
                    continue;
                filter.gameObject.AddComponent<MeshCollider>().sharedMesh = filter.sharedMesh;
            }
        }

