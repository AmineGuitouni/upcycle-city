        static void BuildGround(Transform root, CityMaterials m)
        {
            float midZ = (AvenueSouthZ + NorthRowZ) * 0.5f;
            float lengthZ = NorthRowZ - SouthRowZ + 30f;

            // Asphalt everywhere; raised pavements along both rows of facades and round the square
            Box("Ground_Asphalt", root, new Vector3(10f, -0.5f, midZ), new Vector3(130f, 1f, lengthZ + 20f), m.asphalt);
            foreach (float side in new[] { -1f, 1f })
            {
                float x = side * (FacadeX + KerbX) * 0.5f;
                Box($"Pavement_{(side < 0 ? "West" : "East")}_South", root, new Vector3(x, Kerb * 0.5f, (SouthRowZ + CrossStreetSouthZ) * 0.5f),
                    new Vector3(FacadeX - KerbX, Kerb, CrossStreetSouthZ - SouthRowZ), m.pavement);
                Box($"Pavement_{(side < 0 ? "West" : "East")}_North", root, new Vector3(x, Kerb * 0.5f, (CrossStreetNorthZ + NorthRowZ) * 0.5f),
                    new Vector3(FacadeX - KerbX, Kerb, NorthRowZ - CrossStreetNorthZ), m.pavement);
                Box($"Kerb_{(side < 0 ? "West" : "East")}_South", root, new Vector3(side * (KerbX + 0.1f), Kerb * 0.5f + 0.01f, (SouthRowZ + CrossStreetSouthZ) * 0.5f),
                    new Vector3(0.22f, Kerb + 0.02f, CrossStreetSouthZ - SouthRowZ), m.kerb);
                Box($"Kerb_{(side < 0 ? "West" : "East")}_North", root, new Vector3(side * (KerbX + 0.1f), Kerb * 0.5f + 0.01f, (CrossStreetNorthZ + NorthRowZ) * 0.5f),
                    new Vector3(0.22f, Kerb + 0.02f, NorthRowZ - CrossStreetNorthZ), m.kerb);
            }
            Box("Pavement_SouthEnd", root, new Vector3(0f, Kerb * 0.5f, SouthRowZ + 3f), new Vector3(FacadeX * 2f, Kerb, 6f), m.pavement);
            Box("Pavement_NorthEnd", root, new Vector3(0f, Kerb * 0.5f, NorthRowZ - 3f), new Vector3(FacadeX * 2f, Kerb, 6f), m.pavement);

            // The central promenade and Place du 14 Janvier
            Box("Promenade", root, new Vector3(0f, Kerb * 0.5f, (AvenueSouthZ + AvenueNorthZ) * 0.5f),
                new Vector3(PromenadeHalf * 2f, Kerb, AvenueNorthZ - AvenueSouthZ), m.promenade);
            foreach (float side in new[] { -1f, 1f })
                Box("Promenade_Kerb", root, new Vector3(side * (PromenadeHalf + 0.1f), Kerb * 0.5f + 0.01f, (AvenueSouthZ + AvenueNorthZ) * 0.5f),
                    new Vector3(0.22f, Kerb + 0.02f, AvenueNorthZ - AvenueSouthZ), m.kerb);
            Box("Square_Paving", root, new Vector3(0f, Kerb * 0.5f, SquareZ), new Vector3(SquareHalf * 2f, Kerb, SquareHalf * 2f), m.square);

            // Factory yard behind the east row, reached by the cross street
            Box("FactoryYard", root, new Vector3(48f, 0.01f, -17f), new Vector3(30f, 0.02f, 38f), m.yard, collider: false);

            // Lane markings: dashed centre lines on both carriageways, zebra crossings by the shops and the square
            foreach (float side in new[] { -1f, 1f })
            {
                float laneX = side * (PromenadeHalf + KerbX) * 0.5f;
                for (float z = AvenueSouthZ + 2f; z < AvenueNorthZ - 2f; z += 6f)
                {
                    if (z > CrossStreetSouthZ - 2f && z < CrossStreetNorthZ + 2f)
                        continue;
                    Box("LaneDash", root, new Vector3(laneX, 0.005f, z), new Vector3(0.16f, 0.01f, 3f), m.lane, collider: false);
                }
                foreach (float zebraZ in new[] { -44f, AvenueNorthZ + 2.5f })
                {
                    for (int i = 0; i < 6; i++)
                    {
                        float x = side * (PromenadeHalf + 1f + i * 1.6f + 0.4f);
                        Box("Zebra", root, new Vector3(x, 0.005f, zebraZ), new Vector3(0.8f, 0.01f, 3.4f), m.lane, collider: false);
                    }
                }
            }

            // Map edge: invisible walls round the whole district
            InvisibleWall(root, new Vector3(-44f, 2f, midZ), new Vector3(1f, 4f, lengthZ + 20f));
            InvisibleWall(root, new Vector3(64f, 2f, midZ), new Vector3(1f, 4f, lengthZ + 20f));
            InvisibleWall(root, new Vector3(10f, 2f, SouthRowZ - 14f), new Vector3(110f, 4f, 1f));
            InvisibleWall(root, new Vector3(10f, 2f, NorthRowZ + 14f), new Vector3(110f, 4f, 1f));
        }

