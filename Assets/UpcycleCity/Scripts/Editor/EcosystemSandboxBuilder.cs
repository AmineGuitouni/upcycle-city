        [MenuItem("Upcycle City/Build Phase 2 Ecosystem Sandbox", priority = 15)]
        public static void BuildEcosystemSandbox()
        {
            if (!EditorUtility.DisplayDialog("Build Ecosystem Sandbox",
                    "Rebuild Scenes/EcosystemSandbox.unity on Avenue Habib Bourguiba? The current scene file is replaced.",
                    "Rebuild", "Cancel"))
                return;
            Build();
        }

        /// <summary>Builds and saves the scene without asking (for automation).</summary>
        public static void Build()
        {
            ProjectLayersAndTagsSetup.EnsureAll(logWhenUnchanged: false);
            EnsureFolder("Assets/UpcycleCity/Scenes");
            EnsureFolder(EcosystemSettingsDir);
            EnsureFolder(PlayerSettingsDir);

            // 1. Fresh scene first: NewScene unloads assets loaded before it, which would leave null references
            var scene = EditorSceneManager.NewScene(NewSceneSetup.EmptyScene, NewSceneMode.Single);

            // 2. Data: waste catalog, respirator mask, shops
            WasteCatalog catalog = BuildOrUpdateWasteCatalog();
            EcosystemBalance balance = EnsureBalanceAsset();
            EnsureRespiratorMaskAsset();
            AssetDatabase.SaveAssets();
            ShopContentBuilder.Content shops = ShopContentBuilder.EnsureAll();

            var mats = new CityMaterials();
            Material matSky = LoadMat($"{MaterialsDir}/Sky_Pollution.mat");
            Material matSmoke = LoadMat($"{MaterialsDir}/ChimneySmoke.mat");
            Material matIndicator = CreateRuntimeMaterial("Eco_Indicator", Color.white, 0.35f);   // factory status beacon

            // 3. Systems: sun, grading, pollution, ecosystem, crowd, shop window
            var systemsRoot = new GameObject("Systems");
            Light sun = BuildSystems(systemsRoot.transform, matSky, balance, out CrowdCharacterLibrary charLib);

            // 4. Ground: asphalt, pavements, promenade, square, factory yard, road markings
            var worldRoot = new GameObject("World_Geometry");
            BuildGround(worldRoot.transform, mats);

            // 5. Districts (pollution zones)
            CityDistrict babBhar = CreateDistrict("District_BabBhar", "Bab Bhar End", new Vector3(0f, 0f, -44f), 30f, 22f, 1.1f, 0.6f);
            CityDistrict avenue = CreateDistrict("District_Avenue", "Avenue Centre", new Vector3(0f, 0f, 12f), 30f, 16f, 1.0f, 0.78f);
            CityDistrict square = CreateDistrict("District_Square", "Place du 14 Janvier", new Vector3(0f, 0f, SquareZ), 26f, 12f, 1.2f, 0.82f);
            CityDistrict factory = CreateDistrict("District_FactoryYard", "Factory Yard", new Vector3(48f, 0f, -17f), 20f, 18f, 0.9f, 0.92f);

            // 5b. City pollution grid over every district: cells leak pollution to their neighbours (PollutionGrid)
            var gridGo = new GameObject("PollutionGrid");
            gridGo.transform.SetParent(systemsRoot.transform, false);
            gridGo.AddComponent<PollutionGrid>().FitToZones(12f);

            // 6. Buildings and shops
            var buildingsRoot = new GameObject("Buildings");
            Dictionary<string, GameObject> placed = BuildStreetRows(buildingsRoot.transform);
            var shopsRoot = new GameObject("Shops");
            SetUpShops(shopsRoot.transform, placed, shops, babBhar);

            // 7. Place du 14 Janvier: the Clock Tower in its fountain
            BuildSquare(square);

            // 8. Street furniture: promenade trees, benches, lamps, planters, parked taxis
            BuildStreetFurniture(babBhar, avenue);

            // 9. Pollution sources: municipal bins, the alley, the factory
            var sourcesRoot = new GameObject("Pollution_Sources");
            BuildBinsAndDecay(sourcesRoot.transform, catalog, babBhar, avenue, square, factory);
            BuildFactoryYard(sourcesRoot.transform, catalog, factory, matIndicator, matSmoke);

            // 10. Citizens
            BuildCitizens(systemsRoot.transform, charLib, catalog, avenue);

            // 11. Sorting drop-off on the promenade, just ahead of the player
            BuildSortingHub();
            BinSearchSetup.EnsureLootTable();
            BinSearchSetup.EnsureOrganicMaterial();
            BinSearchSetup.EnsureCompostBin(scene);

            // 12. Seed deterministic starter trash attributed to real causes (matching the curated 23-item Bourguiba layout)
            var seededTrashRoot = new GameObject("Seeded_CauseTrash");
            SeedDeterministicTrash(catalog, seededTrashRoot.transform, WasteSourceKind.Citizen, new Vector3(-1.5f, 0.6f, -38f), 3.4f,
                "Kaskrout Wrap", "Kaskrout Wrap", "Water Bottle", "Glibettes Cone");
            SeedDeterministicTrash(catalog, seededTrashRoot.transform, WasteSourceKind.Citizen, new Vector3(-17.8f, 0.6f, -26f), 1.6f,
                "Espresso Cup", "Tuna Tin", "Espresso Cup");
            SeedDeterministicTrash(catalog, seededTrashRoot.transform, WasteSourceKind.ShopOverflow, new Vector3(16.8f, 0.6f, -48f), 1.8f,
                "Blue Bag", "Espresso Cup", "Espresso Cup", "Harissa Tin");
            SeedDeterministicTrash(catalog, seededTrashRoot.transform, WasteSourceKind.Citizen, new Vector3(1.5f, 0.6f, 6f), 3.6f,
                "Paper Coffee Cup", "Water Bottle", "Newspaper");
            SeedDeterministicTrash(catalog, seededTrashRoot.transform, WasteSourceKind.Citizen, new Vector3(-9f, 0.6f, SquareZ - 14f), 2.6f,
                "Crushed Bottle", "Espresso Cup", "Water Bottle", "Newspaper");
            SeedDeterministicTrash(catalog, seededTrashRoot.transform, WasteSourceKind.UrbanDecay, new Vector3(-27f, 0.7f, -17f), 1.8f,
                "Broken TV", "Old Tyre");
            SeedDeterministicTrash(catalog, seededTrashRoot.transform, WasteSourceKind.FactoryScrap, new Vector3(33.5f, 0.6f, -19.0f), 2.0f,
                "Crushed Can", "Shipping Carton", "Shipping Carton");

            // 13. Player, at the Bab Bhar end of the promenade facing the Clock Tower
            PlacePlayer();

            // 14. Nav mesh the citizens route over and step around things on
            CrowdNavMeshTool.BakeInScene(scene);

            EditorSceneManager.SaveScene(scene, ScenePath);
            AddSceneToBuildSettings(ScenePath);
            AssetDatabase.Refresh();
            Debug.Log($"[Upcycle City] Built the Avenue Habib Bourguiba ecosystem sandbox at {ScenePath} (sun {sun.name}).");
        }

