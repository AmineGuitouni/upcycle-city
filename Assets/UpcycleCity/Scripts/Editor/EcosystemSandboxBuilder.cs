        static void SetUpShops(Transform root, Dictionary<string, GameObject> buildings, ShopContentBuilder.Content shops, CityDistrict district)
        {
            RuntimeAnimatorController controller = shops.keeperController;
            SetUpShop(root, buildings, "shop_cafe", shops.cafe, controller,
                new KeeperSpot { model = "TeacherMale_A", local = new Vector3(0.8f, 0.06f, -9.45f), yaw = 0f, poi = CitizenPoiKind.Cafe });
            SetUpShop(root, buildings, "shop_tools", shops.tools, controller,
                new KeeperSpot { model = "Mechanic", local = new Vector3(-4.3f, 0.06f, -2.4f), yaw = 90f, poi = CitizenPoiKind.ShopWindow });
