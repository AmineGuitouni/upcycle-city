        static GameObject PlaceStaticProp(string assetPath, string name, Transform parent, Vector3 worldPos, Quaternion rotation, float scale,
            bool collider = true)
        {
            GameObject asset = AssetDatabase.LoadAssetAtPath<GameObject>(assetPath);
            if (asset == null)
            {
                Debug.LogWarning($"[Upcycle City] Missing prop {assetPath}");
                return null;
            }

            // Keep the model's own root rotation and scale (Quaternius roots carry a 100× unit scale)
            var instance = (GameObject)PrefabUtility.InstantiatePrefab(asset, parent);
            instance.name = name;
            instance.transform.SetPositionAndRotation(worldPos, rotation * asset.transform.localRotation);
            instance.transform.localScale = asset.transform.localScale * scale;

            if (collider && instance.GetComponentInChildren<Collider>(true) == null)
            {
                Renderer[] rends = instance.GetComponentsInChildren<Renderer>(true);
                if (rends.Length > 0)
                {
                    Bounds b = rends[0].bounds;
                    for (int i = 1; i < rends.Length; i++)
                        b.Encapsulate(rends[i].bounds);
                    BoxCollider box = instance.AddComponent<BoxCollider>();
                    box.center = instance.transform.InverseTransformPoint(b.center);
                    Vector3 lossy = instance.transform.lossyScale;
                    Vector3 localSize = Quaternion.Inverse(instance.transform.rotation) * b.size;
                    box.size = new Vector3(
                        Mathf.Abs(localSize.x) / Mathf.Max(0.01f, Mathf.Abs(lossy.x)),
                        Mathf.Abs(localSize.y) / Mathf.Max(0.01f, Mathf.Abs(lossy.y)),
                        Mathf.Abs(localSize.z) / Mathf.Max(0.01f, Mathf.Abs(lossy.z)));
                }
            }

            GameLayers.SetLayerRecursively(instance, GameLayers.Environment);
            instance.tag = GameTags.Environment;
            instance.isStatic = true;
            return instance;
        }

