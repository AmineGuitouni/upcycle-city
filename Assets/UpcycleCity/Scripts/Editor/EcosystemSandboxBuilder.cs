    /// <summary>
    /// Builds the playable pollution sandbox (<c>Scenes/EcosystemSandbox.unity</c>) on Avenue Habib Bourguiba, Tunis:
    /// a tree-lined promenade between two rows of Bab Bhar style buildings, running from the Bab Bhar end
    /// (where the player starts, by the shops) north to Place du 14 Janvier and its Clock Tower and fountain.
    /// A cross street leads east to a factory yard (the smokestack and its scrubber) and west to a neglected alley.
    ///
    /// Every pollution loop from the earlier sandbox is kept: four districts with pollution zones, citizens who
    /// litter, overflowing municipal bins, urban decay, the factory, the sorting drop-off. On top: walk-in shops
    /// with shopkeeper NPCs (café, quincaillerie, épicerie) that sell tools and food boosts, and the RÉCUP
    /// buy-back point whose scale buys trash for coins. Models come from <c>Art/UpcycleProps/Bourguiba</c>
    /// (generated by <c>Tools/Blender/export_bourguiba.py</c>); shop data from <see cref="ShopContentBuilder"/>.
    /// </summary>
